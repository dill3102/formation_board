export function shortcutTable() {
  return h('table', { class: 'help-table' },
    h('tbody', {}, SHORTCUTS.map(([key, desc]) => h('tr', {},
      // 入れ子の配列にしない (古い dom.js でも崩れないように)
      h('th', {}, key.split(' / ').flatMap((k, i) => (i > 0 ? [' / ', h('kbd', {}, k)] : [h('kbd', {}, k)]))),
      h('td', {}, desc),
    ))),
  );
}

