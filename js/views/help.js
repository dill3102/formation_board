export function render(root, [sectionId]) {
  const list = sections();
  const toc = h('nav', { class: 'help-toc', 'aria-label': '目次' },
    list.map((s) => h('button', { class: 'btn btn-small', type: 'button', onclick: () => scrollTo(s.id) }, s.title)));

  const sectionEls = new Map(list.map((s) => [s.id,
    h('section', { class: 'card help-section', id: `help-${s.id}` }, h('h2', {}, s.title), s.body)]));

  function scrollTo(id) {
    sectionEls.get(id)?.scrollIntoView({ behavior: 'smooth', block: 'start' });
  }

  root.append(
    h('section', { class: 'card' },
      h('h1', {}, '使い方'),
      h('p', {}, '監督・コーチが、選手を登録して、試合・練習ごとの配置と作戦をホワイトボード感覚で作れるツールです。'),
      toc,
    ),
    ...sectionEls.values(),
  );

  // ルーターが表示後にページ先頭へスクロールするので、その後で目的のセクションへ
  if (sectionId) setTimeout(() => sectionEls.get(sectionId)?.scrollIntoView({ block: 'start' }), 0);
}
